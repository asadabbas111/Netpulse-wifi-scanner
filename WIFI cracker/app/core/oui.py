def lookup_vendor(mac: str | None) -> str:
    if not mac:
        return "Unknown"
    cleaned = re_clean(mac)
    if len(cleaned) < 6:
        return "Unknown"
    # IEEE locally-administered bit (2nd least-significant bit of first octet)
    # Phones often use randomized MACs — OUI lookup would be misleading.
    first = int(cleaned[0:2], 16)
    if first & 0x02:
        return "Randomized MAC"
    return _OUI.get(cleaned[:6].upper(), "Unknown")


def re_clean(mac: str) -> str:
    return "".join(ch for ch in mac.upper() if ch in "0123456789ABCDEF")
